$updates = @{
    '124A' = $hindi124A.Trim()
    '124B' = $hindi124B.Trim()
    '124C' = $hindi124C.Trim()
}

$updatedCount = 0
foreach ($article in $p5.articles) {
    $artId = $article.id.ToString().Trim()
    if ($updates.ContainsKey($artId)) {
        $article.hindi = $updates[$artId]
        Write-Host "Updated Article $artId - hindi length: $($article.hindi.Length)"
        $updatedCount++
    }
}

Write-Host "Total updated: $updatedCount"

# Save
$jsonOut = $json | ConvertTo-Json -Depth 10
[System.IO.File]::WriteAllText($jsonPath, $jsonOut, $utf8NoBom)
Write-Host "Saved: $jsonPath"

# Verify
$verify = [System.IO.File]::ReadAllText($jsonPath, [System.Text.Encoding]::UTF8) | ConvertFrom-Json
$p5v = $verify | Where-Object { $_.partId -eq 'V' }
foreach ($id in @('124A','124B','124C')) {
    $art = $p5v.articles | Where-Object { $_.id -eq $id }
    Write-Host "Art $id hindi length: $(if($art.hindi){$art.hindi.Length}else{0})"
    Write-Host "  Preview: $(if($art.hindi){$art.hindi.Substring(0,[Math]::Min(80,$art.hindi.Length))})"
}
